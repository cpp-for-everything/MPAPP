// ---- Section identity --------------------------------------------------
// Ordered exactly as the reference navigation bar. `count` is the menu
// length; `login` is the pre-auth pseudo-section.
enum class section : int {
    information = 0,   // Информация
    health,            // Здравно осигуряване
    grades,            // Заверки и оценки
    sport,             // Спорт
    scholarship,       // Стипендии
    housing,           // Общежития
    payments,          // Плащания
    identification,    // Идентификация
    history,           // История на влизанията
    help,              // Помощна информация
    count
};

inline const char* section_title(section s) {
    switch (s) {
        case section::information:    return "Информация";
        case section::health:         return "Здравно осигуряване";
        case section::grades:         return "Заверки и оценки";
        case section::sport:          return "Спорт";
        case section::scholarship:    return "Стипендии";
        case section::housing:        return "Общежития";
        case section::payments:       return "Плащания";
        case section::identification: return "Идентификация";
        case section::history:        return "История на влизанията";
        case section::help:           return "Помощна информация";
        default:                      return "";
    }
}

// ---- Value records -----------------------------------------------------

struct attribute {
    std::string key;
    std::string value;
};

struct status_row {       // "Хронология на студентското състояние"
    std::string course;   // Курс
    std::string year;     // Уч. год.
    std::string semester; // Зав. сем.
    std::string state;    // Състояние
    std::string reason;   // Причина
    std::string order_no; // Зап. №
    std::string order_date; // Зап. дата
};

struct grade_group {           // one academic semester
    std::string title;         // "1 сем.", "8 сем. (текущ)"
    std::vector<std::string> entries; // one line per discipline
};

struct login_row {            // "Последни влизания" / "грешни опита"
    std::string index;
    std::string when;
    std::string ip;
    std::string agent;
};

struct help_topic {
    std::string heading;
    std::string body;
};

// ---- The student record ------------------------------------------------

